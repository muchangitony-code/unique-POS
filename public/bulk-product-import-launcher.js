(() => {
  'use strict';

  const BUTTON_ID = 'button-bulk-add-products';
  const MODAL_ID = 'uniquepos-bulk-import-overlay';
  const TOKEN_KEYS = ['uniquepos.token', 'auth_token', 'token'];

  // The POS may authenticate with an HttpOnly session cookie. Do not attach the
  // first token found in localStorage before trying that session: a stale Bearer
  // token overrides a perfectly valid cookie and produces "Invalid or expired token".
  function storedTokens() {
    const seen = new Set();
    return TOKEN_KEYS.map((key) => localStorage.getItem(key)).filter((token) => {
      if (!token || seen.has(token)) return false;
      seen.add(token);
      return true;
    });
  }

  async function authenticatedFetch(url, options) {
    const base = Object.assign({}, options || {});
    base.credentials = 'include';
    base.headers = Object.assign({}, base.headers || {});

    // Prefer the authenticated browser session used by the live POS.
    let response = await fetch(url, base);
    if (response.status !== 401) return response;

    // Some deployments use Bearer authentication instead. Retry only after the
    // cookie/session attempt fails, rather than allowing a stale token to poison it.
    for (const token of storedTokens()) {
      const headers = Object.assign({}, base.headers, { Authorization: `Bearer ${token}` });
      response = await fetch(url, Object.assign({}, base, { headers }));
      if (response.status !== 401) return response;
    }
    return response;
  }

  function closeModal() {
    document.getElementById(MODAL_ID)?.remove();
  }

  function setStatus(message, kind) {
    const status = document.querySelector('#uniquepos-bulk-import-status');
    if (!status) return;
    status.textContent = message || '';
    status.style.color = kind === 'error' ? '#b91c1c' : kind === 'success' ? '#15803d' : '#475569';
  }

  function openImporter() {
    if (document.getElementById(MODAL_ID)) return;
    const overlay = document.createElement('div');
    overlay.id = MODAL_ID;
    overlay.style.cssText = 'position:fixed;inset:0;z-index:99999;background:rgba(15,23,42,.62);display:flex;align-items:center;justify-content:center;padding:20px';
    overlay.innerHTML = `
      <div role="dialog" aria-modal="true" style="width:min(680px,100%);background:#fff;color:#1e293b;border-radius:14px;box-shadow:0 24px 70px rgba(0,0,0,.35);padding:28px;font-family:Inter,Arial,sans-serif">
        <div style="display:flex;justify-content:space-between;gap:20px;align-items:flex-start">
          <div><h2 style="margin:0 0 8px;font-size:25px">Bulk Add Products</h2><p style="margin:0;color:#64748b;line-height:1.5">Upload your CSV, Excel or supported PDF product list. Existing POS fields are preserved, blank product codes can be generated by the server, and opening stock is imported as stock.</p></div>
          <button type="button" data-ub-close style="border:0;background:transparent;font-size:28px;line-height:1;cursor:pointer;color:#475569">×</button>
        </div>
        <div style="margin-top:22px;padding:16px;border:1px solid #cbd5e1;border-radius:10px;background:#f8fafc">
          <strong>Supported columns:</strong> Product Code, Barcode, Product Name, Category, Brand, Supplier, Unit, Cost Price, Selling Price, VAT, Reorder Level, Opening Stock, Location, Description, Image URL.
        </div>
        <input id="uniquepos-bulk-import-file" type="file" accept=".csv,.xlsx,.xls,.pdf,text/csv,application/vnd.openxmlformats-officedocument.spreadsheetml.sheet,application/vnd.ms-excel,application/pdf" style="margin-top:20px;width:100%;padding:12px;border:1px solid #94a3b8;border-radius:8px" />
        <div id="uniquepos-bulk-import-status" style="min-height:24px;margin-top:14px;font-size:14px"></div>
        <div style="display:flex;justify-content:flex-end;gap:12px;margin-top:20px">
          <button type="button" data-ub-close style="padding:11px 18px;border:1px solid #cbd5e1;border-radius:8px;background:#fff;cursor:pointer;font-weight:600">Cancel</button>
          <button type="button" id="uniquepos-bulk-import-submit" style="padding:11px 20px;border:0;border-radius:8px;background:#2563eb;color:#fff;cursor:pointer;font-weight:700">Import Products</button>
        </div>
      </div>`;
    document.body.appendChild(overlay);
    overlay.addEventListener('click', (event) => { if (event.target === overlay || event.target.closest('[data-ub-close]')) closeModal(); });
    overlay.querySelector('#uniquepos-bulk-import-submit').addEventListener('click', startImport);
  }

  async function readError(response) {
    try {
      const data = await response.json();
      return data?.error || data?.message || JSON.stringify(data);
    } catch (_) {
      return response.statusText || `HTTP ${response.status}`;
    }
  }

  async function startImport() {
    const input = document.getElementById('uniquepos-bulk-import-file');
    const submit = document.getElementById('uniquepos-bulk-import-submit');
    const file = input?.files?.[0];
    if (!file) { setStatus('Choose a file first.', 'error'); return; }
    submit.disabled = true;
    submit.style.opacity = '.65';
    try {
      setStatus('Uploading and validating your file…');
      const form = new FormData();
      form.append('file', file, file.name || 'product-import');
      form.append('source_name', file.name || 'Uploaded file');
      const upload = await authenticatedFetch('/api/products/imports/upload-and-parse', { method: 'POST', body: form });
      if (!upload.ok) throw new Error(await readError(upload));
      const job = await upload.json();
      const jobId = job?.id || job?.job?.id || job?.data?.id;
      if (!jobId) throw new Error('The server did not return an import job ID.');
      setStatus('File validated. Importing products…');
      const start = await authenticatedFetch(`/api/products/imports/${encodeURIComponent(jobId)}/start`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ on_duplicate: 'update', recategorize: false })
      });
      if (!start.ok) throw new Error(await readError(start));
      const result = await start.json();
      const created = result?.created_count ?? result?.created ?? result?.summary?.created_count;
      const updated = result?.updated_count ?? result?.updated ?? result?.summary?.updated_count;
      setStatus(`Import complete${created != null || updated != null ? `: ${created || 0} created, ${updated || 0} updated.` : '.'}`, 'success');
      window.setTimeout(() => { closeModal(); window.location.reload(); }, 900);
    } catch (error) {
      setStatus(error?.message || 'Bulk import failed.', 'error');
    } finally {
      if (submit && document.body.contains(submit)) { submit.disabled = false; submit.style.opacity = '1'; }
    }
  }

  function install() {
    const add = document.querySelector('[data-testid="button-add-product"]');
    if (!add || !add.parentElement) return false;
    let button = document.querySelector(`[data-testid="${BUTTON_ID}"]`);
    if (!button) {
      button = document.createElement('button');
      button.type = 'button';
      button.dataset.testid = BUTTON_ID;
      button.textContent = 'Bulk Add Products';
      button.style.cssText = 'height:40px;padding:0 16px;border:1px solid #94a3b8;border-radius:6px;background:transparent;color:inherit;font-weight:600;cursor:pointer;pointer-events:auto;opacity:1';
      add.parentElement.insertBefore(button, add);
    }
    button.dataset.action = 'bulk-import-products';
    button.onclick = (event) => { event.preventDefault(); event.stopPropagation(); openImporter(); };
    return true;
  }

  const observer = new MutationObserver(install);
  observer.observe(document.documentElement, { childList: true, subtree: true });
  document.addEventListener('DOMContentLoaded', install);
  install();
})();
