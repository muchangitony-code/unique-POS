unique_matches AS (
  SELECT p.id AS product_id, p.product_name, p.selling_price, MAX(s.opening_stock) AS opening_stock
  FROM products p
  JOIN source s
    ON lower(regexp_replace(trim(p.product_name), '[^a-z0-9]+', '', 'g')) = lower(regexp_replace(trim(s.product_name), '[^a-z0-9]+', '', 'g'))
   AND COALESCE(p.selling_price, 0)::numeric = COALESCE(s.selling_price, 0)::numeric
  GROUP BY p.id, p.product_name, p.selling_price
),
ambiguous AS (
  SELECT lower(regexp_replace(trim(product_name), '[^a-z0-9]+', '', 'g')) AS name_key,
         COALESCE(selling_price, 0)::numeric AS selling_price
  FROM products
  GROUP BY 1,2
  HAVING COUNT(*) > 1
),
safe_matches AS (
  SELECT um.* FROM unique_matches um
  WHERE NOT EXISTS (
    SELECT 1 FROM ambiguous a
    WHERE a.name_key = lower(regexp_replace(trim(um.product_name), '[^a-z0-9]+', '', 'g'))
      AND a.selling_price = COALESCE(um.selling_price, 0)::numeric
  )
),
main_branch AS (
  SELECT id FROM branches WHERE code = 'MAIN' ORDER BY id LIMIT 1
)
INSERT INTO product_stock (product_id, branch_id, current_stock, min_stock)
SELECT sm.product_id, mb.id, sm.opening_stock, COALESCE(p.min_stock, 0)
FROM safe_matches sm
JOIN products p ON p.id = sm.product_id
CROSS JOIN main_branch mb
WHERE sm.opening_stock > 0
ON CONFLICT (branch_id, product_id) DO UPDATE SET
  current_stock = GREATEST(product_stock.current_stock, EXCLUDED.current_stock),
  min_stock = GREATEST(COALESCE(product_stock.min_stock, 0), EXCLUDED.min_stock);

UPDATE products p
SET current_stock = COALESCE((SELECT SUM(ps.current_stock) FROM product_stock ps WHERE ps.product_id = p.id), 0)
WHERE EXISTS (SELECT 1 FROM product_stock ps WHERE ps.product_id = p.id);

COMMIT;
